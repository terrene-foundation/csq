#!/usr/bin/env python3
"""Freshness check: csq/gen/schemas/acl-manifests.json `__app-acl__` vs its sources.

`check-acl-default-membership.py` reads ONLY the generated manifest. If that file
is stale or hand-edited relative to `csq/permissions/**/*.toml`, the ratchet
evaluates a surface the app does not have. This script compares the two EXACTLY, in
both directions: every `[[permission]]` (identifier, commands.allow/deny, scope,
description when the TOML states one), every `[[set]]` (identifier, permissions)
and the `[default]` block must match `__app-acl__`, with nothing extra on either side.

The `autogenerated/` TOMLs are tauri-build's output for the command list passed to
`AppManifest::new().commands(&[...])` in `csq/build.rs`. That literal is parsed
too: each command must have exactly its `allow-<cmd>` / `deny-<cmd>` pair
(underscores become dashes), and no other autogenerated permission may exist. If
the literal cannot be found the check exits 2 rather than skipping.

Exit 0 = fresh. Exit 1 = mismatch (names the item). Exit 2 = could not evaluate.
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
from pathlib import Path
from typing import NoReturn

REPO_ROOT = Path(__file__).resolve().parent.parent
PERMISSIONS = REPO_ROOT / "csq" / "permissions"
MANIFESTS = REPO_ROOT / "csq" / "gen" / "schemas" / "acl-manifests.json"
BUILD_RS = REPO_ROOT / "csq" / "build.rs"


def die(msg: str) -> NoReturn:
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(2)


def str_list(value: object, what: str) -> list[str]:
    if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
        die(f"{what} must be a list of strings, got {value!r}")
    return list(value)


def norm_scope(raw: object, what: str) -> dict[str, list[str]] | None:
    """Comparable form of a permission `scope`: None when it has no entries, else the
    non-empty `allow` / `deny` sides as sorted canonical-JSON strings. A shape this
    check does not understand exits 2 -- ignoring it would hide a widened scope."""
    if raw is None:
        return None
    if not isinstance(raw, dict):
        die(f"{what}: scope is not an object")
    unknown = sorted(set(raw) - {"allow", "deny"})
    if unknown:
        die(f"{what}: scope has unknown key(s) {unknown!r}")
    out: dict[str, list[str]] = {}
    for side in ("allow", "deny"):
        items = raw.get(side)
        if items is None:
            continue
        if not isinstance(items, list):
            die(f"{what}: scope.{side} is not a list")
        if items:
            out[side] = sorted(json.dumps(i, sort_keys=True) for i in items)
    return out or None


def load_sources() -> tuple[dict, dict, dict | None, list[Path]]:
    files = sorted(PERMISSIONS.glob("*.toml")) + sorted((PERMISSIONS / "autogenerated").glob("*.toml"))
    if not files:
        die("no permission TOML files found under csq/permissions -- refusing to compare against nothing.")
    perms: dict[str, dict] = {}
    sets: dict[str, dict] = {}
    default: dict | None = None
    for f in files:
        try:
            doc = tomllib.loads(f.read_text())
        except (OSError, tomllib.TOMLDecodeError) as e:
            die(f"{f.relative_to(REPO_ROOT)} unreadable or not valid TOML: {e}")
        for p in doc.get("permission", []):
            ident = p.get("identifier")
            if not isinstance(ident, str) or not ident:
                die(f"{f.name}: [[permission]] without a string identifier")
            if ident in perms:
                die(f"{f.name}: duplicate permission {ident!r}")
            cmds = p.get("commands", {})
            if not isinstance(cmds, dict):
                die(f"{f.name}: {ident} commands is not a table")
            perms[ident] = {
                "allow": str_list(cmds.get("allow", []), f"{ident} commands.allow"),
                "deny": str_list(cmds.get("deny", []), f"{ident} commands.deny"),
                "description": p.get("description"),
                "scope": norm_scope(p.get("scope"), f"{f.name}: {ident}"),
            }
        for s in doc.get("set", []):
            ident = s.get("identifier")
            if not isinstance(ident, str) or not ident:
                die(f"{f.name}: [[set]] without a string identifier")
            if ident in sets:
                die(f"{f.name}: duplicate set {ident!r}")
            sets[ident] = {"permissions": str_list(s.get("permissions", []), f"set {ident} permissions")}
        if "default" in doc:
            if default is not None or not isinstance(doc["default"], dict):
                die(f"{f.name}: duplicate or non-table [default]")
            default = {"permissions": str_list(doc["default"].get("permissions", []), "default permissions")}
    return perms, sets, default, files


def build_rs_commands() -> list[str]:
    try:
        text = BUILD_RS.read_text()
    except OSError as e:
        die(f"csq/build.rs unreadable: {e}")
    m = re.search(r"AppManifest::new\(\)\s*\.commands\(\s*&\[(.*?)\]\s*\)", text, re.S)
    if not m:
        die("cannot derive the app command list from csq/build.rs (no `AppManifest::new().commands(&[...])` literal); "
            "refusing to skip the autogenerated comparison.")
    cmds = re.findall(r'"([A-Za-z0-9_]+)"', m.group(1))
    if not cmds:
        die("csq/build.rs app-manifest command literal is empty or not string literals.")
    return cmds


def main() -> int:
    try:
        manifests = json.loads(MANIFESTS.read_text())
    except (OSError, json.JSONDecodeError) as e:
        die(f"{MANIFESTS.relative_to(REPO_ROOT)} unreadable or not valid JSON: {e}")
    app = manifests.get("__app-acl__") if isinstance(manifests, dict) else None
    if not isinstance(app, dict) or not isinstance(app.get("permissions"), dict):
        die("__app-acl__ missing or malformed in the manifests.")
    m_perms = app["permissions"]
    m_sets = app.get("permission_sets") or {}
    if not isinstance(m_sets, dict):
        die("__app-acl__ permission_sets is not an object.")

    perms, sets, default, _files = load_sources()
    problems: list[str] = []

    for ident in sorted(set(perms) | set(m_perms)):
        if ident not in m_perms:
            problems.append(f"permission {ident!r} is in csq/permissions but NOT in the generated manifest")
            continue
        if ident not in perms:
            problems.append(f"permission {ident!r} is in the generated manifest but NOT in csq/permissions")
            continue
        mp, sp = m_perms[ident], perms[ident]
        mc = mp.get("commands") if isinstance(mp, dict) else None
        if not isinstance(mc, dict):
            die(f"manifest permission {ident!r} has no commands object")
        for kind in ("allow", "deny"):
            mine = str_list(mc.get(kind, []), f"manifest {ident} commands.{kind}")
            if sorted(mine) != sorted(sp[kind]):
                problems.append(f"permission {ident!r} commands.{kind} differ: manifest={sorted(mine)} toml={sorted(sp[kind])}")
        if sp["description"] is not None and mp.get("description") != sp["description"]:
            problems.append(f"permission {ident!r} description differs")
        m_scope = norm_scope(mp.get("scope"), f"manifest permission {ident!r}")
        if m_scope != sp["scope"]:
            problems.append(f"permission {ident!r} scope differs: manifest={m_scope} toml={sp['scope']}")

    for ident in sorted(set(sets) | set(m_sets)):
        if ident not in m_sets:
            problems.append(f"set {ident!r} is in csq/permissions but NOT in the generated manifest")
        elif ident not in sets:
            problems.append(f"set {ident!r} is in the generated manifest but NOT in csq/permissions")
        else:
            mm = str_list((m_sets[ident] or {}).get("permissions", []), f"manifest set {ident} permissions")
            if sorted(mm) != sorted(sets[ident]["permissions"]):
                problems.append(f"set {ident!r} members differ: manifest={sorted(mm)} toml={sorted(sets[ident]['permissions'])}")

    m_default = app.get("default_permission")
    m_default_members = None if m_default is None else str_list((m_default or {}).get("permissions", []), "manifest default permissions")
    s_default_members = None if default is None else default["permissions"]
    if (m_default_members is None) != (s_default_members is None) or (
        m_default_members is not None and sorted(m_default_members) != sorted(s_default_members or [])
    ):
        problems.append(f"default permission differs: manifest={m_default_members} toml={s_default_members}")

    # build.rs command list <-> autogenerated/ permissions, both directions.
    expected: set[str] = set()
    for c in build_rs_commands():
        d = c.replace("_", "-")
        expected |= {f"allow-{d}", f"deny-{d}"}
    auto_ids: set[str] = set()
    for f in sorted((PERMISSIONS / "autogenerated").glob("*.toml")):
        auto_ids |= {p["identifier"] for p in tomllib.loads(f.read_text()).get("permission", [])}
    for ident in sorted(expected - auto_ids):
        problems.append(f"build.rs command implies {ident!r} but csq/permissions/autogenerated has no such permission")
    for ident in sorted(auto_ids - expected):
        problems.append(f"autogenerated permission {ident!r} has no matching command in csq/build.rs")

    if problems:
        print("ACL MANIFEST STALE — csq/gen/schemas/acl-manifests.json __app-acl__ does not match its sources.\n")
        for p in problems:
            print(f"  - {p}")
        print("\nRegenerate by building the desktop feature (tauri-build rewrites the manifest), then re-run the ACL ratchet.")
        return 1
    print(f"ACL MANIFEST FRESH — {len(perms)} permissions, {len(sets)} sets match __app-acl__.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except SystemExit:
        raise
    except Exception as e:  # noqa: BLE001 -- a crash is a failed gate, never exit 1
        die(f"could not evaluate: {type(e).__name__}: {e}")
